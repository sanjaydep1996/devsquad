"""Chaos Lab & Self-Healing CI: Server rack outage simulator and autonomous test hardening."""

import datetime
import random
import time
import uuid
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class ChaosIncident:
    """Represents an active or historical chaos incident."""
    incident_id: str
    fault_type: str  # 'LATENCY_SPIKE', 'FLAKY_ENDPOINT', 'CIRCUIT_BREAKER_TRIP', 'SCHEMA_DRIFT', 'DB_LOCK_CONTENTION'
    service_name: str
    severity: str  # 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'
    injected_at: str
    status: str  # 'TRIGGERED', 'DIAGNOSING', 'AUTO_HEALING', 'HEALED'
    error_message: str
    impact_description: str
    healing_plan: Optional[Dict[str, Any]] = None


@dataclass
class HealingPlan:
    """Remediation plan generated by Alpha BE and verified by Gamma QA."""
    incident_id: str
    root_cause: str
    patch_code: str
    regression_test_code: str
    resilience_pattern: str  # e.g., 'exponential_backoff_jitter', 'circuit_breaker', 'schema_adapter'
    verified_by_qa: bool
    recovery_time_ms: int
    summary: str


class ChaosLab:
    """Simulates production and CI outages, then orchestrates squad self-healing."""

    FAULT_PRESETS = {
        "LATENCY_SPIKE": {
            "severity": "MEDIUM",
            "message": "upstream service responded in 4820ms (exceeds SLA 500ms)",
            "impact": "Requests queueing up, worker pool starvation risk",
            "pattern": "timeout_guard_with_fallback",
        },
        "FLAKY_ENDPOINT": {
            "severity": "HIGH",
            "message": "HTTP 503 Service Unavailable (intermittent failure rate 34%)",
            "impact": "Unreliable user sessions, intermittent failed PR staging tasks",
            "pattern": "exponential_backoff_jitter",
        },
        "CIRCUIT_BREAKER_TRIP": {
            "severity": "CRITICAL",
            "message": "5 consecutive 500 Internal Server Errors from Payment/Auth service",
            "impact": "Cascading dependency crash across multi-agent worker nodes",
            "pattern": "circuit_breaker_state_machine",
        },
        "SCHEMA_DRIFT": {
            "severity": "HIGH",
            "message": "KeyError: 'billing_account_id' missing from external webhook payload",
            "impact": "Uncaught deserialization exception causing pipeline abort",
            "pattern": "defensive_schema_adapter",
        },
        "DB_LOCK_CONTENTION": {
            "severity": "HIGH",
            "message": "OperationalError: database is locked (concurrent worktree write lock)",
            "impact": "Staging tasks blocked on SQLite transaction locks",
            "pattern": "wal_mode_and_retry_decorator",
        },
    }

    def __init__(self):
        self.active_incidents: Dict[str, ChaosIncident] = {}
        self.incident_history: List[ChaosIncident] = []

    def list_presets(self) -> List[Dict[str, str]]:
        """Returns all available chaos fault injection presets."""
        return [
            {
                "fault_type": k,
                "severity": v["severity"],
                "description": v["message"],
                "impact": v["impact"],
                "resilience_pattern": v["pattern"],
            }
            for k, v in self.FAULT_PRESETS.items()
        ]

    def inject_fault(
        self,
        fault_type: str = "FLAKY_ENDPOINT",
        service_name: str = "DevSquad Relaying Engine",
    ) -> ChaosIncident:
        """Injects a simulated infrastructure failure into the studio server rack."""
        preset = self.FAULT_PRESETS.get(fault_type, self.FAULT_PRESETS["FLAKY_ENDPOINT"])
        incident_id = f"chaos-{uuid.uuid4().hex[:8]}"
        now = datetime.datetime.now(datetime.timezone.utc).isoformat()

        incident = ChaosIncident(
            incident_id=incident_id,
            fault_type=fault_type,
            service_name=service_name,
            severity=preset["severity"],
            injected_at=now,
            status="TRIGGERED",
            error_message=f"[{service_name}] {preset['message']}",
            impact_description=preset["impact"],
        )

        self.active_incidents[incident_id] = incident
        self.incident_history.append(incident)
        return incident

    def trigger_self_healing(self, incident_id: str) -> HealingPlan:
        """Executes squad self-healing: Alpha BE creates patch, Gamma QA writes regression tests."""
        incident = self.active_incidents.get(incident_id)
        if not incident:
            # Check history
            for inc in self.incident_history:
                if inc.incident_id == incident_id:
                    incident = inc
                    break

        if not incident:
            raise KeyError(f"Chaos incident '{incident_id}' not found.")

        incident.status = "AUTO_HEALING"
        start_ms = time.time()

        preset = self.FAULT_PRESETS.get(incident.fault_type, self.FAULT_PRESETS["FLAKY_ENDPOINT"])
        pattern = preset["pattern"]

        # Generate targeted resilience patch
        patch_code, test_code, root_cause = self._generate_resilience_artifacts(
            incident.fault_type, incident.service_name
        )

        recovery_time = int((time.time() - start_ms) * 1000) + random.randint(180, 420)

        plan = HealingPlan(
            incident_id=incident_id,
            root_cause=root_cause,
            patch_code=patch_code,
            regression_test_code=test_code,
            resilience_pattern=pattern,
            verified_by_qa=True,
            recovery_time_ms=recovery_time,
            summary=f"Auto-healed {incident.fault_type} via {pattern} with verified regression tests.",
        )

        incident.status = "HEALED"
        incident.healing_plan = {
            "root_cause": plan.root_cause,
            "resilience_pattern": plan.resilience_pattern,
            "verified_by_qa": plan.verified_by_qa,
            "recovery_time_ms": plan.recovery_time_ms,
            "summary": plan.summary,
            "patch_code": plan.patch_code,
            "regression_test_code": plan.regression_test_code,
        }

        return plan

    def _generate_resilience_artifacts(
        self, fault_type: str, service_name: str
    ) -> tuple[str, str, str]:
        """Synthesizes self-healing patch code and regression tests."""
        if fault_type == "LATENCY_SPIKE":
            root_cause = "Missing bounded timeout and non-blocking fallback on external API invocation."
            patch = (
                "import asyncio\n\n"
                "async def fetch_with_timeout(url: str, timeout_sec: float = 0.500):\n"
                "    try:\n"
                "        return await asyncio.wait_for(client.get(url), timeout=timeout_sec)\n"
                "    except asyncio.TimeoutError:\n"
                "        logger.warning('Upstream latency exceeded SLA; returning degraded cached payload.')\n"
                "        return get_degraded_cache_fallback(url)\n"
            )
            test = (
                "def test_timeout_fallback():\n"
                "    with mock.patch('client.get', side_effect=asyncio.TimeoutError):\n"
                "        res = asyncio.run(fetch_with_timeout('https://api.internal/data'))\n"
                "        assert res['status'] == 'cached_fallback'\n"
            )
        elif fault_type == "CIRCUIT_BREAKER_TRIP":
            root_cause = "Cascading downstream failures without circuit breaker protection."
            patch = (
                "class CircuitBreaker:\n"
                "    def __init__(self, failure_threshold: int = 5, recovery_timeout: float = 30.0):\n"
                "        self.failure_count = 0\n"
                "        self.state = 'CLOSED'  # 'CLOSED', 'OPEN', 'HALF_OPEN'\n"
                "        self.last_failure_time = 0.0\n\n"
                "    def call(self, fn, *args, **kwargs):\n"
                "        if self.state == 'OPEN':\n"
                "            if time.time() - self.last_failure_time > 30:\n"
                "                self.state = 'HALF_OPEN'\n"
                "            else:\n"
                "                raise CircuitOpenException('Circuit open; call rejected.')\n"
                "        try:\n"
                "            res = fn(*args, **kwargs)\n"
                "            self.state = 'CLOSED'\n"
                "            self.failure_count = 0\n"
                "            return res\n"
                "        except Exception:\n"
                "            self.failure_count += 1\n"
                "            if self.failure_count >= 5:\n"
                "                self.state = 'OPEN'\n"
                "                self.last_failure_time = time.time()\n"
                "            raise\n"
            )
            test = (
                "def test_circuit_breaker_trips():\n"
                "    cb = CircuitBreaker(failure_threshold=2)\n"
                "    for _ in range(2):\n"
                "        try: cb.call(lambda: 1/0)\n"
                "        except: pass\n"
                "    assert cb.state == 'OPEN'\n"
            )
        elif fault_type == "SCHEMA_DRIFT":
            root_cause = "Unchecked dictionary key access on dynamic third-party JSON payload."
            patch = (
                "def parse_webhook_payload(data: dict) -> dict:\n"
                "    # Defensive schema adapter with default fallback\n"
                "    account_id = data.get('billing_account_id') or data.get('account_id', 'anonymous')\n"
                "    return {\n"
                "        'account_id': str(account_id),\n"
                "        'events': data.get('events', []),\n"
                "        'timestamp': data.get('timestamp') or datetime.utcnow().isoformat(),\n"
                "    }\n"
            )
            test = (
                "def test_schema_drift_tolerant():\n"
                "    dirty_payload = {'events': ['login']}\n"
                "    res = parse_webhook_payload(dirty_payload)\n"
                "    assert res['account_id'] == 'anonymous'\n"
            )
        else:  # FLAKY_ENDPOINT or DB_LOCK_CONTENTION default
            root_cause = "Intermittent transient network or concurrency errors without retry jitter."
            patch = (
                "import time, random\n\n"
                "def retry_with_exponential_backoff(max_attempts=3, base_delay=0.1, max_delay=1.0):\n"
                "    def decorator(fn):\n"
                "        def wrapper(*args, **kwargs):\n"
                "            for attempt in range(1, max_attempts + 1):\n"
                "                try:\n"
                "                    return fn(*args, **kwargs)\n"
                "                except Exception as e:\n"
                "                    if attempt == max_attempts:\n"
                "                        raise\n"
                "                    jitter = random.uniform(0, 0.05)\n"
                "                    sleep_sec = min(max_delay, base_delay * (2 ** (attempt - 1))) + jitter\n"
                "                    time.sleep(sleep_sec)\n"
                "        return wrapper\n"
                "    return decorator\n"
            )
            test = (
                "def test_flaky_retry_healed():\n"
                "    calls = {'count': 0}\n"
                "    @retry_with_exponential_backoff(max_attempts=3)\n"
                "    def fragile():\n"
                "        calls['count'] += 1\n"
                "        if calls['count'] < 2: raise ConnectionResetError('Transient')\n"
                "        return 'ok'\n"
                "    assert fragile() == 'ok'\n"
                "    assert calls['count'] == 2\n"
            )

        return patch, test, root_cause
